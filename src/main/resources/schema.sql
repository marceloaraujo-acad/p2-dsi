CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome        VARCHAR(100)  NOT NULL,
    usuario     VARCHAR(50)   NOT NULL,
    -- Nas aulas a senha era MD5 em CHAR(32). MD5 e inadequado para senhas;
    -- aqui guardamos "pbkdf2_sha256$iteracoes$salt$hash" (Base64), gerado em Java.
    senha_hash  VARCHAR(200)  NOT NULL,
    criado_em   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_usuario        PRIMARY KEY (id),
    CONSTRAINT uq_usuario_login  UNIQUE (usuario),
    CONSTRAINT ck_usuario_nome   CHECK (CHAR_LENGTH(TRIM(nome)) > 0),
    CONSTRAINT ck_usuario_login  CHECK (CHAR_LENGTH(TRIM(usuario)) >= 3)
);
